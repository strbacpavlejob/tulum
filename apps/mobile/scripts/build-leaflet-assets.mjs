#!/usr/bin/env node

/**
 * Writes components/map/leafletAssets.ts: the Leaflet and Leaflet.markercluster
 * JavaScript and CSS as strings, so the native maps' WebView page works
 * without loading anything from unpkg. Run it after changing the leaflet or
 * leaflet.markercluster versions in package.json:
 *
 *   pnpm --dir apps/mobile run build:leaflet
 */

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);

const read = (specifier) => readFileSync(require.resolve(specifier), "utf8");
// The code is inlined into <script> and <style> tags, which must not close early.
const inline = (code) => code.replace(/<\/(script|style)/gi, "<\\/$1");

const leaflet = require("leaflet/package.json").version;
const markercluster = require("leaflet.markercluster/package.json").version;

const assets = {
  LEAFLET_JS: inline(read("leaflet/dist/leaflet.js")),
  LEAFLET_CSS: inline(read("leaflet/dist/leaflet.css")),
  MARKERCLUSTER_JS: inline(
    read("leaflet.markercluster/dist/leaflet.markercluster.js"),
  ),
  MARKERCLUSTER_CSS: inline(
    read("leaflet.markercluster/dist/MarkerCluster.css"),
  ),
};

const output = [
  `// Generated by scripts/build-leaflet-assets.mjs from leaflet@${leaflet} and`,
  `// leaflet.markercluster@${markercluster}. Don't edit; rerun the script instead.`,
  "",
  ...Object.entries(assets).map(
    ([name, code]) => `export const ${name}: string = ${JSON.stringify(code)};`,
  ),
  "",
].join("\n");

const target = fileURLToPath(
  new URL("../components/map/leafletAssets.ts", import.meta.url),
);
writeFileSync(target, output);
console.log(
  `Wrote ${target} (leaflet ${leaflet}, markercluster ${markercluster}, ${output.length} bytes)`,
);
